-- ファームがまずない種類を一覧から外す（設計 16章）。
-- 元データで「ファームはたぶんある」とされていたもののうち、ヘッドホン・ターンテーブル、マウス・ポインター、
-- PC本体（OS の新しいバージョンは別の仕組みで知らせる）、充電器・電源タップ、従来型の照明、ピンスポット、スモーク等。
-- すでに誰かが登録している機種は残す。
DELETE FROM models
WHERE firmware = 'maybe'
  AND (category, sub) IN (
    VALUES ('音響', 'その他音響'), ('PC', 'プレゼン周辺'), ('PC', 'ノートPC'), ('PC', 'タブレット'), ('PC', 'デスクトップPC'),
           ('電源・特機', '電源'), ('照明', 'その他'), ('照明', 'ピンスポット'), ('照明', '効果機材'))
  AND id NOT IN (SELECT model_id FROM gear WHERE model_id IS NOT NULL);
